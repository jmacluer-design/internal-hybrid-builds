// Builds preview/vendor/lua-bundle.js: every Lua file the browser preview runs (the REAL resource files + the preview glue), as one
// JS object { "sim/world.lua": "...", ... }, so the preview works offline from a static folder with no fetches.
//   node preview/tools/build_bundle.mjs          write the bundle
//   node preview/tools/build_bundle.mjs --check  exit 1 when the bundle is stale (used by the tests)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');             // hybrids/outbreak
const RES = path.join(ROOT, 'fivem', 'outbreak');
const OUT = path.join(ROOT, 'preview', 'vendor', 'lua-bundle.js');

export function collect() {
  const files = {};
  for (const dir of ['sim', 'data', 'shared']) {
    for (const f of fs.readdirSync(path.join(RES, dir)).filter(n => n.endsWith('.lua')).sort()) {
      files[`${dir}/${f}`] = fs.readFileSync(path.join(RES, dir, f), 'utf8');
    }
  }
  files['preview/glue.lua'] = fs.readFileSync(path.join(ROOT, 'preview', 'glue.lua'), 'utf8');
  return files;
}

export function render(files) {
  const keys = Object.keys(files).sort();
  const body = keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(files[k])}`).join(',\n');
  return `// GENERATED by preview/tools/build_bundle.mjs: do not edit. ${keys.length} Lua files from fivem/outbreak/{sim,data,shared} + preview/glue.lua.\nwindow.OUTBREAK_LUA = {\n${body}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(collect());
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('lua-bundle.js is STALE: run node preview/tools/build_bundle.mjs'); process.exit(1); }
    console.log('lua-bundle.js is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
